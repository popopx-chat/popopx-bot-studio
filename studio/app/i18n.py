def normalize_locale(raw: Optional[str]) -> str:
    """Map an arbitrary language tag onto one of :data:`LOCALES`, else ``""``."""
    if not raw:
        return ""
    tag = str(raw).strip().replace("_", "-").lower()
    if not tag:
        return ""
    if tag in {locale.lower() for locale in LOCALES}:
        for locale in LOCALES:
            if locale.lower() == tag:
                return locale
    if tag in _TAG_ALIASES:
        return _TAG_ALIASES[tag]
    base = tag.split("-")[0]
    if base in _TAG_ALIASES:
        return _TAG_ALIASES[base]
    for locale in LOCALES:
        if locale.lower() == base:
            return locale
    return ""


def detect_locale(candidates: Iterable[Any]) -> str:
    """First candidate that maps onto a supported locale, else the fallback."""
    for candidate in candidates:
        if isinstance(candidate, (list, tuple)):
            for item in candidate:
                locale = normalize_locale(str(item).split(";")[0].strip())
                if locale:
                    return locale
            continue
        locale = normalize_locale(str(candidate).split(";")[0].strip())
        if locale:
            return locale
    return FALLBACK_LOCALE


def parse_accept_language(header: str) -> List[str]:
    """``"zh-CN,zh;q=0.9,en;q=0.8"`` -> ordered tag list."""
    tags: List[Tuple[float, int, str]] = []
    for order, raw in enumerate((header or "").split(",")):
        piece = raw.strip()
        if not piece:
            continue
        tag, _, quality = piece.partition(";")
        try:
            weight = float(quality.split("=", 1)[1]) if "=" in quality else 1.0
        except ValueError:
            weight = 0.0
        tags.append((weight, -order, tag.strip()))
    return [tag for _weight, _neg, tag in sorted(tags, reverse=True)]


def placeholders(text: str) -> set:
    return set(_PLACEHOLDER_RE.findall(text or ""))


